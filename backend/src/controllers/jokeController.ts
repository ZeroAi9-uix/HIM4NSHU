export async function toggleFavorite(req: AuthRequest, res: Response) {
  try {
    const { id } = req.params;
    const userId = req.user?.id;

    if (!userId) {
      return res.status(401).json({ error: 'Authentication required.' });
    }

    const user = await User.findById(userId);
    if (!user) {
      return res.status(404).json({ error: 'User not found.' });
    }

    const jokeObjId = id as any;
    const favIdx = user.favorites.indexOf(jokeObjId);

    let isFavorite = false;
    if (favIdx > -1) {
      user.favorites.splice(favIdx, 1);
    } else {
      user.favorites.push(jokeObjId);
      isFavorite = true;
      await User.findByIdAndUpdate(userId, { $inc: { xp: 15 } }); // Reward bookmarking
    }

    await user.save();
    return res.json({ isFavorite, favorites: user.favorites });
  } catch (error) {
    console.error('Favorite toggle error:', error);
    return res.status(500).json({ error: 'Server error during favorite toggle.' });
  }
}

