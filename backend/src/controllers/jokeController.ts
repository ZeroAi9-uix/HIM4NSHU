import { Response } from 'express';
import { AuthRequest } from '../middlewares/auth';
import Joke from '../models/Joke';
import Comment from '../models/Comment';
import User from '../models/User';
import { generateJoke } from '../config/gemini';

export async function generateJokeRoute(req: AuthRequest, res: Response) {
  try {
    const { category, roastTopic } = req.query;
    const isRoast = category === 'roast';

    const cleanCategory = ['dark', 'funny', 'lame', 'romance', 'roast'].includes(category as string)
      ? (category as 'dark' | 'funny' | 'lame' | 'romance' | 'roast')
      : 'funny';

    const jokeText = await generateJoke(cleanCategory, roastTopic as string);

    // Save AI-generated joke to database so community features (likes, comments, favorites) work
    const savedJoke = new Joke({
      text: jokeText,
      category: cleanCategory,
      creator: 'AI',
      isQuiz: false
    });

    await savedJoke.save();

    // Reward XP for generating joke if authenticated
    if (req.user?.id) {
      await User.findByIdAndUpdate(req.user.id, { $inc: { xp: 10 } });
    }

    return res.json({
      joke: savedJoke
    });
  } catch (error) {
    console.error('Joke generation route error:', error);
    return res.status(500).json({ error: 'Failed to generate joke.' });
  }
}

export async function getTrendingJokes(req: AuthRequest, res: Response) {
  try {
    const jokes = await Joke.find({ isQuiz: false })
      .sort({ likes: -1, createdAt: -1 })
      .limit(10);
    return res.json({ jokes });
  } catch (error) {
    console.error('Trending jokes fetch error:', error);
    return res.status(500).json({ error: 'Failed to fetch trending jokes.' });
  }
}

export async function getRandomJoke(req: AuthRequest, res: Response) {
  try {
    const count = await Joke.countDocuments({ isQuiz: false });
    if (count === 0) {
      // Create first joke
      const jokeText = await generateJoke('funny');
      const saved = await Joke.create({ text: jokeText, category: 'funny', creator: 'AI' });
      return res.json({ joke: saved });
    }
    const randomIdx = Math.floor(Math.random() * count);
    const joke = await Joke.findOne({ isQuiz: false }).skip(randomIdx);
    return res.json({ joke });
  } catch (error) {
    console.error('Random joke fetch error:', error);
    return res.status(500).json({ error: 'Failed to fetch random joke.' });
  }
}

export async function getDailyJoke(req: AuthRequest, res: Response) {
  try {
    const startOfToday = new Date();
    startOfToday.setHours(0, 0, 0, 0);

    // Check if daily joke exists for today
    let dailyJoke = await Joke.findOne({
      category: 'general',
      createdAt: { $gte: startOfToday }
    });

    if (!dailyJoke) {
      const jokeText = await generateJoke('funny');
      dailyJoke = new Joke({
        text: `[Daily Laugh] ${jokeText}`,
        category: 'general',
        creator: 'AI'
      });
      await dailyJoke.save();
    }

    return res.json({ joke: dailyJoke });
  } catch (error) {
    console.error('Daily joke fetch error:', error);
    return res.status(500).json({ error: 'Failed to fetch daily joke.' });
  }
}

export async function toggleLike(req: AuthRequest, res: Response) {
  try {
    const { id } = req.params;
    const userId = req.user?.id;

    if (!userId) {
      return res.status(401).json({ error: 'Authentication required to vote.' });
    }

    const joke = await Joke.findById(id);
    if (!joke) {
      return res.status(404).json({ error: 'Joke not found.' });
    }

    // Toggle upvote
    const userObjId = userId as any;
    const likedIdx = joke.likes.indexOf(userObjId);
    const dislikedIdx = joke.dislikes.indexOf(userObjId);

    if (likedIdx > -1) {
      // Already liked, remove it
      joke.likes.splice(likedIdx, 1);
    } else {
      // Add like and remove dislike if exists
      joke.likes.push(userObjId);
      if (dislikedIdx > -1) {
        joke.dislikes.splice(dislikedIdx, 1);
      }
      // Give XP to author if generated by user, or minor XP to voter
      await User.findByIdAndUpdate(userId, { $inc: { xp: 5 } });
    }

    await joke.save();
    return res.json({ joke });
  } catch (error) {
    console.error('Like toggle error:', error);
    return res.status(500).json({ error: 'Server error during like update.' });
  }
}

